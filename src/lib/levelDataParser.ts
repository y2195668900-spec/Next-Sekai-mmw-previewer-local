/**
 * Sonolus LevelData -> custom score JSON.
 *
 * LevelData is the JSON document exported by MikuMikuWorld4UC / PySekaiEngine:
 *
 *   { "bgmOffset": seconds, "entities": [ { archetype, data: [...], name? } ] }
 *
 * Each entity has a `data` array of `{ name, value }` or `{ name, ref }` entries.
 * `ref` values are names produced by a base-16 id counter, so they must be
 * resolved through the entity `name` field instead of being parsed as numbers.
 *
 * Chart structure is recovered from the `next` linked list on note entities:
 * `Connector` and `SimLine` are derived data and are ignored, matching the
 * reference importer. `AnchorNote` is a hidden shape vertex (no sprite, no
 * judgement). `TransientHiddenTickNote` entries are generated by the editor on
 * export and are explicitly ignored on import by MikuMikuWorld4UC
 * (`archetype.find("Transient") == npos`); dropping them makes a LevelData
 * export of a chart parse into exactly the same structure as the equivalent USC
 * export instead of adding hundreds of duplicate hold-body ticks.
 */

import {
  BaseType,
  Category,
  CustomScoreBuilder,
  EventType,
  TICKS_PER_BEAT,
  directionFromNumber,
  lineTypeFromConnectorEase,
  relativeSpeedRatio,
  quantizeSpeedSegments,
  valueAt,
  type ScoreStep,
  type SpeedChange,
} from './customScore'

type LevelDataEntity = {
  archetype: string
  name?: string
  data?: Array<{ name: string; value?: number | string; ref?: string }>
}

type LevelDataDocument = {
  bgmOffset?: number
  entities?: LevelDataEntity[]
}

export type LevelDataParseResult = {
  json: string
  /** `bgmOffset`: seconds the chart is shifted against the audio. */
  offsetSeconds: number
  bpm: number
  noteCount: number
}

const EASE_LINEAR = 1

const GUIDE_COLOR_BASE = 101

function readNumber(value: unknown, fallback = 0) {
  if (typeof value === 'number' && Number.isFinite(value)) {
    return value
  }
  if (typeof value === 'string') {
    const parsed = Number.parseFloat(value)
    if (Number.isFinite(parsed)) {
      return parsed
    }
  }
  return fallback
}

function entityValues(entity: LevelDataEntity) {
  const values = new Map<string, number | string>()
  if (!Array.isArray(entity.data)) {
    return values
  }
  for (const entry of entity.data) {
    if (!entry || typeof entry.name !== 'string') {
      continue
    }
    if (entry.ref !== undefined) {
      values.set(entry.name, entry.ref)
    } else if (entry.value !== undefined) {
      values.set(entry.name, entry.value)
    }
  }
  return values
}

/** `segmentKind`: 1/2 = judged (normal/critical), +50 = dummy, 101..108 = guide colours. */
function isGuideSegmentKind(kind: number) {
  return kind >= GUIDE_COLOR_BASE && kind < GUIDE_COLOR_BASE + 8
}

function segmentCritical(kind: number, fallback: boolean) {
  if (kind <= 0) {
    return fallback
  }
  if (isGuideSegmentKind(kind)) {
    return false
  }
  const base = kind > 50 ? kind - 50 : kind
  if (base === 1) {
    return false
  }
  if (base === 2) {
    return true
  }
  return fallback
}

function isDamageKind(kind: number) {
  if (kind <= 0) {
    return false
  }
  const base = kind > 50 ? kind - 50 : kind
  return base === 3
}

/** Archetype grammar: `[Fake] (Anchor | (Critical|Normal) [Head][Tail] [Trace][Flick] (Tap|Release|Tick|Damage)) Note`. */
function classifyArchetype(archetype: string) {
  return {
    anchor: archetype === 'AnchorNote',
    transient: archetype === 'TransientHiddenTickNote',
    critical: archetype.startsWith('Critical'),
    head: archetype.includes('Head'),
    tail: archetype.includes('Tail'),
    trace: archetype.includes('Trace'),
    flick: archetype.includes('Flick'),
    damage: archetype.includes('Damage'),
    tick: archetype.includes('Tick'),
  }
}

export function parseLevelData(text: string): LevelDataParseResult {
  let root: unknown
  try {
    root = JSON.parse(text)
  } catch {
    throw new Error('LevelData 文件不是合法的 JSON。')
  }
  if (!root || typeof root !== 'object' || Array.isArray(root)) {
    throw new Error('LevelData 文件根节点必须是对象。')
  }

  const document = root as LevelDataDocument
  if (!Array.isArray(document.entities)) {
    throw new Error('LevelData 文件缺少 entities 数组。')
  }
  const entities = document.entities.filter(
    (entity): entity is LevelDataEntity => !!entity && typeof entity === 'object' && typeof entity.archetype === 'string',
  )
  const offsetSeconds = readNumber(document.bgmOffset, 0)

  const values = entities.map(entityValues)
  const byName = new Map<string, number>()
  entities.forEach((entity, index) => {
    if (typeof entity.name === 'string' && entity.name && !byName.has(entity.name)) {
      byName.set(entity.name, index)
    }
  })

  const resolve = (ref: unknown) => {
    if (typeof ref === 'number' && Number.isInteger(ref) && ref >= 0 && ref < entities.length) {
      return ref
    }
    if (typeof ref === 'string') {
      const byEntityName = byName.get(ref)
      if (byEntityName !== undefined) {
        return byEntityName
      }
      // Some producers reference entities by their array index in base 16.
      const parsed = Number.parseInt(ref, 16)
      if (Number.isInteger(parsed) && parsed >= 0 && parsed < entities.length) {
        return parsed
      }
    }
    return -1
  }

  const valueOf = (index: number, key: string) => (index >= 0 ? values[index]?.get(key) : undefined)

  // --- tempo & time scale -------------------------------------------------
  const tempoChanges: SpeedChange[] = []
  const groupOrder: string[] = []
  const groupTimelines = new Map<string, SpeedChange[]>()
  const groupIndexByName = new Map<string, number>()

  for (let index = 0; index < entities.length; index += 1) {
    const archetype = entities[index].archetype
    if (archetype === '#BPM_CHANGE') {
      const beat = readNumber(valueOf(index, '#BEAT'), Number.NaN)
      const bpm = readNumber(valueOf(index, '#BPM'), Number.NaN)
      if (Number.isFinite(beat) && Number.isFinite(bpm) && bpm > 0) {
        tempoChanges.push({ tick: Math.round(beat * TICKS_PER_BEAT), value: bpm })
      }
    } else if (archetype === '#TIMESCALE_GROUP') {
      const name = entities[index].name
      if (typeof name === 'string' && !groupTimelines.has(name)) {
        groupTimelines.set(name, [])
        groupIndexByName.set(name, index)
        groupOrder.push(name)
      }
    }
  }

  if (tempoChanges.length === 0) {
    tempoChanges.push({ tick: 0, value: 120 })
  }
  tempoChanges.sort((left, right) => left.tick - right.tick)
  const bpm = tempoChanges[0].value

  // Time scale changes are linked through `first` and then each change's `next`.
  for (const name of groupOrder) {
    const timeline = groupTimelines.get(name)!
    const groupIndex = groupIndexByName.get(name)!
    let cursor = resolve(valueOf(groupIndex, 'first'))
    const guard = new Set<number>()
    while (cursor >= 0 && entities[cursor].archetype === '#TIMESCALE_CHANGE' && !guard.has(cursor)) {
      guard.add(cursor)
      const beat = readNumber(valueOf(cursor, '#BEAT'), Number.NaN)
      const timeScale = readNumber(valueOf(cursor, '#TIMESCALE'), Number.NaN)
      // 负/零流速必须保留：它属于这条 version 自己的曲线，渲染器按 version
      // 积分时钟，负值就是这些音符的时钟往回走（见 `SpeedLayers`）。
      if (Number.isFinite(beat) && Number.isFinite(timeScale)) {
        timeline.push({ tick: Math.round(beat * TICKS_PER_BEAT), value: timeScale })
      }
      cursor = resolve(valueOf(cursor, 'next'))
    }
    timeline.sort((left, right) => left.tick - right.tick)
  }

  // 短于 1/96 拍的速度段拉长到 1/96 拍（见 `quantizeSpeedSegments`），
  // 让成对的极短正负尖峰互相抵消。
  const speedLayers = groupOrder.map((name) => quantizeSpeedSegments(groupTimelines.get(name) ?? []))

  const groupIndexOfRef = (ref: unknown) => {
    const index = resolve(ref)
    if (index < 0) {
      return -1
    }
    const name = entities[index].name
    return typeof name === 'string' ? groupOrder.indexOf(name) : -1
  }

  // 参考曲线只服务静态图表渲染器（`speedRatio`）和没有 version 的输入；
  // 渲染器不用它给音符定位，因此取第一条非空曲线，不做投票合并。
  const referenceTimeline = speedLayers.find((timeline) => timeline.length > 0) ?? []
  const speedFor = (groupRef: unknown, tick: number): { layer: number; ratio: number } => {
    const layer = groupIndexOfRef(groupRef)
    if (layer < 0) {
      return { layer: -1, ratio: 1 }
    }
    return { layer, ratio: relativeSpeedRatio(valueAt(referenceTimeline, tick), valueAt(speedLayers[layer], tick)) }
  }

  // --- note chains -------------------------------------------------------
  const isNoteArchetype = (index: number) => entities[index].archetype.endsWith('Note')
  // Export-time generated helper entities. The reference importer skips any
  // archetype containing `Transient`, and so do we: they duplicate the hold
  // bodies that the `next` chain already describes.
  const isTransient = (index: number) => entities[index].archetype.includes('Transient')

  const realNotes: number[] = []
  for (let index = 0; index < entities.length; index += 1) {
    if (isNoteArchetype(index) && !isTransient(index)) {
      realNotes.push(index)
    }
  }

  // `next` occasionally resolves to a non-note entity (`Connector`,
  // `#TIMESCALE_CHANGE`) because the reference names collide with array
  // indices; only links between real notes describe a hold.
  const nextOf = new Map<number, number>()
  for (const index of realNotes) {
    const target = resolve(valueOf(index, 'next'))
    if (target >= 0 && isNoteArchetype(target) && !isTransient(target)) {
      nextOf.set(index, target)
    }
  }

  const isChainTarget = new Set(nextOf.values())
  const heads = realNotes.filter((index) => !isChainTarget.has(index))
  const chains: number[][] = []
  const chainOf = new Map<number, number>()
  for (const head of heads) {
    const chain: number[] = []
    let cursor: number | undefined = head
    while (cursor !== undefined && cursor >= 0 && !chainOf.has(cursor)) {
      chain.push(cursor)
      chainOf.set(cursor, chains.length)
      cursor = nextOf.get(cursor)
    }
    chains.push(chain)
  }

  // --- emission ----------------------------------------------------------
  const builder = new CustomScoreBuilder()
  builder.setSpeedLayers(speedLayers)
  for (const change of tempoChanges) {
    builder.addEvent(EventType.Bpm, change.tick, change.value)
  }
  // 参考曲线仍以 HiSpeed 事件下发（静态图表渲染器用），预览器只在音符没有
  // `speedLayer` 时才回退到它。
  for (const change of referenceTimeline) {
    builder.addEvent(EventType.HiSpeed, change.tick, change.value)
  }

  const beatOf = (index: number) => readNumber(valueOf(index, '#BEAT'), 0)
  const laneOf = (index: number) => readNumber(valueOf(index, 'lane'), 0)
  const sizeOf = (index: number) => readNumber(valueOf(index, 'size'), 0.5)
  const kindOf = (index: number) => Math.trunc(readNumber(valueOf(index, 'segmentKind'), 0))
  // `style` is the per-note colour of the Next-RUSH engine (0 = default,
  // 1..8 = neutral, red, green, blue, yellow, purple, cyan, black). MMW itself
  // drops it on import, but the preview can tint the sprite with it.
  const styleOf = (index: number) => Math.trunc(readNumber(valueOf(index, 'style'), 0))
  // Sonolus per-note hit sound (`effectKind`, 0..10). MMW's own importer throws
  // this away; the previewer forwards it so a charter can give a single note a
  // different sample (e.g. a critical note that should play the normal tap).
  const effectOf = (index: number) => {
    const effect = Math.trunc(readNumber(valueOf(index, 'effectKind'), 0))
    return effect < 0 ? 0 : effect > 10 ? 10 : effect
  }
  const guideColorOf = (index: number) => {
    const kind = kindOf(index)
    return isGuideSegmentKind(kind) ? kind - GUIDE_COLOR_BASE : -1
  }
  // LevelData has no explicit fade field. The exporter stores the per-joint
  // alpha in `segmentAlpha`; a chain that ramps it encodes a fade, a uniform
  // alpha of 1 encodes none.
  const guideFadeOf = (chain: number[]) => {
    if (chain.length < 2) {
      return 1
    }
    const first = readNumber(valueOf(chain[0], 'segmentAlpha'), 1)
    const last = readNumber(valueOf(chain[chain.length - 1], 'segmentAlpha'), 1)
    if (Math.abs(first - last) < 1e-3) {
      return 1
    }
    return last < first ? 0 : 2
  }
  const easeOf = (index: number) => Math.trunc(readNumber(valueOf(index, 'connectorEase'), EASE_LINEAR))
  const groupRefOf = (index: number) => valueOf(index, '#TIMESCALE_GROUP')

  /**
   * Absolute flick direction carried by Sonolus LevelData `direction`:
   * 1 = left, 2 = right, 3 = down, 4 = down-left, 5 = down-right, else 0.
   * The legacy `directionFromNumber` above collapses the vertical variants
   * because MMW only models diagonal flicks, so the raw value is forwarded too
   * and the renderer mirrors / quarter-turns the arrow sprite.
   */
  const absoluteDirectionFromNumber = (value: unknown): number => {
    const direction = Math.trunc(readNumber(value, 0))
    return direction >= 1 && direction <= 5 ? direction : 0
  }

  const stepOf = (
    index: number,
    baseType: number,
    critical: boolean,
    direction = 0,
    flickDirection = 0,
  ): ScoreStep => {
    const tick = Math.round(beatOf(index) * TICKS_PER_BEAT)
    const speed = speedFor(groupRefOf(index), tick)
    return {
      laneCenter: laneOf(index),
      laneSize: sizeOf(index),
      tick,
      critical,
      baseType,
      direction,
      flickDirection,
      lineType: lineTypeFromConnectorEase(easeOf(index)),
      speedLayer: speed.layer,
      speedRatio: speed.ratio,
      style: styleOf(index),
      hitEffect: effectOf(index),
    }
  }

  /** Tap base type derived from the archetype. */
  const tapBaseType = (archetype: string) => {
    const info = classifyArchetype(archetype)
    if (info.trace) {
      return info.flick ? BaseType.FrictionFlick : BaseType.Friction
    }
    return info.flick ? BaseType.Flick : BaseType.Normal
  }

  for (let chainIndex = 0; chainIndex < chains.length; chainIndex += 1) {
    const chain = chains[chainIndex]

    // --- standalone tap ------------------------------------------------
    if (chain.length === 1) {
      const index = chain[0]
      const archetype = entities[index].archetype
      const info = classifyArchetype(archetype)
      if (info.anchor) {
        // A lone AnchorNote is a shape-only artefact with nothing to draw.
        continue
      }
      if (info.damage) {
        // `DamageNote` joins the judgement chain (combo / PERFECT popup) but
        // never spawns hit effects; its hit sound is opt-in (damage 音效).
        // and it normally sits far outside the stage (lane ±17..±24). It still
        // has to be *drawn* — with its own sprite and its own group speed — so
        // it is emitted as a flagged tap and the renderer keeps it off the
        // judgement paths.
        builder.addTap({
          ...stepOf(index, BaseType.Damage, false),
          category: Category.Damage,
          damage: true,
        })
        continue
      }
      const kind = kindOf(index)
      builder.addTap(
        stepOf(
          index,
          tapBaseType(archetype),
          isDamageKind(kind) ? false : segmentCritical(kind, info.critical),
          info.flick ? directionFromNumber(valueOf(index, 'direction')) : 0,
          info.flick ? absoluteDirectionFromNumber(valueOf(index, 'direction')) : 0,
        ),
      )
      continue
    }

    // --- guide path ----------------------------------------------------
    // Guide chains are drawn as an unbounded "TouchLine" trail. The guide colour
    // comes from the `segmentKind` (101..108) and the fade from the per-joint
    // `segmentAlpha` ramp, so both are forwarded to the renderer.
    if (chain.some((index) => isGuideSegmentKind(kindOf(index)))) {
      const guideHead = chain.find((index) => isGuideSegmentKind(kindOf(index))) ?? chain[0]
      const guideColor = guideColorOf(guideHead)
      const guideFade = guideFadeOf(chain)
      builder.addGuidePath(
        chain.map((index) => ({
          ...stepOf(index, BaseType.Guide, false),
          guideColor,
          guideFade,
        })),
      )
      continue
    }

    // --- hold chain ----------------------------------------------------
    const steps: ScoreStep[] = []

    for (let position = 0; position < chain.length; position += 1) {
      const index = chain[position]
      const info = classifyArchetype(entities[index].archetype)
      const kind = kindOf(index)
      const critical = segmentCritical(kind, info.critical)
      const isFirst = position === 0
      const isLast = position + 1 === chain.length
      const direction = info.flick ? directionFromNumber(valueOf(index, 'direction')) : 0
      const flickDirection = info.flick ? absoluteDirectionFromNumber(valueOf(index, 'direction')) : 0

      let baseType: number
      if (isFirst) {
        // The first element must classify as a slide START on the native side.
        // `FrictionHideLong` starts a hold whose head is hidden ("judgeType:
        // none" in USC), `Long`/`FrictionLong` start a judged one.
        baseType = info.anchor ? BaseType.FrictionHideLong : info.trace ? BaseType.FrictionLong : BaseType.Long
      } else if (isLast) {
        // The last element must classify as a slide END; `FrictionHide` hides it.
        if (info.anchor) {
          baseType = BaseType.FrictionHide
        } else if (info.trace && info.flick) {
          baseType = BaseType.FrictionFlick
        } else if (info.flick) {
          baseType = BaseType.Flick
        } else if (info.trace) {
          baseType = BaseType.Friction
        } else {
          baseType = BaseType.Normal
        }
      } else {
        // Intermediate AnchorNotes bend the hold body without drawing a note.
        baseType = info.anchor ? BaseType.HiddenConnection : BaseType.Base
      }

      // Hidden vertices are shape only: they never take part in judgement. They
      // must still keep the chain's criticality though, otherwise a critical
      // hold with a hidden (AnchorNote) head or tail loses its golden body.
      steps.push(stepOf(index, baseType, critical, direction, flickDirection))
    }

    if (steps.length >= 2) {
      builder.addChain(steps)
    } else if (steps.length === 1) {
      builder.addTap(steps[0])
    }
  }

  return {
    json: builder.buildJson(),
    offsetSeconds,
    bpm,
    noteCount: builder.noteCount,
  }
}

export { Category }
